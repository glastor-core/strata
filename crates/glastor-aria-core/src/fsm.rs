//! Deterministic Finite State Machine (FSM) core abstractions.
//!
//! Provides the foundational contracts for event-driven, framework-agnostic
//! UI behavior and DOM action emission.

use core::fmt::Debug;

/// Result of an FSM state transition.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TransitionResult<S, A> {
    /// The resulting state after the transition.
    pub next_state: S,
    /// Side-effect actions that the UI layer must execute (e.g. DOM manipulation, focus shifts).
    pub actions: Vec<A>,
}

impl<S, A> TransitionResult<S, A> {
    /// Creates a new transition result without side-effect actions.
    pub fn state_only(next_state: S) -> Self {
        Self {
            next_state,
            actions: Vec::new(),
        }
    }

    /// Creates a new transition result with actions.
    pub fn with_actions(next_state: S, actions: Vec<A>) -> Self {
        Self {
            next_state,
            actions,
        }
    }
}

/// Core trait representing a deterministic headless state machine.
pub trait StateMachine: Sized {
    /// The state type of this machine.
    type State: Clone + PartialEq + Eq + Debug;
    /// The event type consumed by this machine.
    type Event: Debug;
    /// The actionable side effects generated by state transitions.
    type Action: Clone + PartialEq + Eq + Debug;

    /// Returns the current state of the machine.
    fn state(&self) -> &Self::State;

    /// Dispatches an event into the state machine, mutating internal state
    /// and returning the emitted actions.
    fn transition(&mut self, event: Self::Event) -> Vec<Self::Action>;

    /// Pure transition function calculating the next state and actions without mutating `self`.
    fn next_transition(&self, event: &Self::Event) -> TransitionResult<Self::State, Self::Action>;
}
